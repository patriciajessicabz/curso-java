package org.example.aula2;

public class ExerciciosAritmeticos1 {
    static void main() {
        // 1- Crie variáveis para dois números inteiros de valor a = 10 e b = 3 e
        // mostre na tela: soma, subtração, multiplicação, divisão e resto.

        int a = 10;
        int b = 3;

        System.out.println("Soma: " + (a + b));
        System.out.println("Subtração: " + (a - b));
        System.out.println("Multiplicação: " + (a * b));
        System.out.println("Divisão: " + ((double) a / b));
        System.out.println("Resto: " + (a % b));


    }
}
